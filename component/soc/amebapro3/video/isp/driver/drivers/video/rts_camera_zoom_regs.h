#ifndef _RTS_CAMERA_ZOOM_REGS_H
#define _RTS_CAMERA_ZOOM_REGS_H

#define ZOOM_SYS_REG_BASE 0x0
#define ZOOM_SYS_CONTROL (ZOOM_SYS_REG_BASE + 0x0000)
#define ZOOM_SYS_SPEED_CTRL (ZOOM_SYS_REG_BASE + 0x0004)
#define ZOOM_SYS_LAST_BREAK (ZOOM_SYS_REG_BASE + 0x0008)
#define ZOOM_SYS_DATA_ENABLE (ZOOM_SYS_REG_BASE + 0x000C)
#define ZOOM_SYS_DATA_DELAY (ZOOM_SYS_REG_BASE + 0x0010)
#define ZOOM_SYS_IMAGE_MODE_SEL (ZOOM_SYS_REG_BASE + 0x0018)
#define ZOOM_SYS_IMAGE_AI_CHAN_SEL (ZOOM_SYS_REG_BASE + 0x0020)
#define ZOOM_SYS_YUV_TRAN_CTRL (ZOOM_SYS_REG_BASE + 0x0028)

#define YUV422TORGB_REG_BASE 0x400
#define YUV2RGB0 (YUV422TORGB_REG_BASE + 0x0000)
#define YUV2RGB1 (YUV422TORGB_REG_BASE + 0x0004)
#define YUV2RGB2 (YUV422TORGB_REG_BASE + 0x0008)
#define YUV2RGB3 (YUV422TORGB_REG_BASE + 0x000C)
#define YUV2RGB4 (YUV422TORGB_REG_BASE + 0x0010)
#define YUV2RGB_YOFFSET (YUV422TORGB_REG_BASE + 0x0014)

#define ZOOM_REG_BASE 0xC00
#define ZOOM_CH0_CTRL (ZOOM_REG_BASE + 0x0000)
#define ZOOM_CH0_CROP_START (ZOOM_REG_BASE + 0x0004)
#define ZOOM_CH0_OUTPUT_SIZE (ZOOM_REG_BASE + 0x0008)
#define ZOOM_CH0_COEF0 (ZOOM_REG_BASE + 0x0010)
#define ZOOM_CH0_COEF1 (ZOOM_REG_BASE + 0x0014)
#define ZOOM_CH0_COEF2 (ZOOM_REG_BASE + 0x0018)
#define ZOOM_CH0_COEF3 (ZOOM_REG_BASE + 0x001C)
#define ZOOM_CH0_COEF4 (ZOOM_REG_BASE + 0x0020)
#define ZOOM_CH0_UP_LINE_SPACE (ZOOM_REG_BASE + 0x0028)
#define ZOOM_CH0_STEP_V (ZOOM_REG_BASE + 0x0048)
#define ZOOM_CH0_STEP_H (ZOOM_REG_BASE + 0x004C)
#define ZOOM_CH0_REG_LOAD (ZOOM_REG_BASE + 0x0024)
/* rts3921 V1 per-channel spacing (rts3917 used 0x80) */
#define ZOOM_V1_CH_REG_OFFSET 0x400   /* ch0 → ch1 */
#define ZOOM_V1_CH_REG_STEP   0x100   /* ch1 → ch2 → ch3 */

#define IVE_REG_BASE 0x800
#define IVE_ENABLE (IVE_REG_BASE + 0x0000)
#define IVE_NORM_MEAN (IVE_REG_BASE + 0x0004)
#define IVE_NORM_SCALE (IVE_REG_BASE + 0x0008)
#define IVE_QUANT_LEN (IVE_REG_BASE + 0x000C)
#define IVE_ASYM_INV_SCALE (IVE_REG_BASE + 0x0010)
#define IVE_ASYM_ZERO_POINT (IVE_REG_BASE + 0x0014)

/* ZOOM_SYS_YUV_TRAN_CTRL */
#define LIMIT_MASK 0x11

/* ZOOM_CH0_CTRL */
#define ENABLE_ZOOM  0x1
#define DISABLE_ZOOM 0x0   /* rts3921: clear enable bit; rts3917 used 0x2 */
/* ZOOM_CH0_REG_LOAD */
#define LOAD_ZOOM_PARAM 0x1

#endif /* _RTS_CAMERA_ZOOM_REGS_H */
