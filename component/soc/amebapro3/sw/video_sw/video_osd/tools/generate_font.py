"""Generate Ameba OSD Sans ASCII bitmaps; no target build or runtime font engine.

Requires Pillow 12.2.0 (FreeType 2.14.3 for byte-identical regeneration).
Input: LiberationSans-Bold.ttf from the official liberation-fonts-ttf-2.1.5
archive. Emit the C header to stdout, or use --check to verify an existing header.
"""

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT_SHA256 = "788abee4c806d660e8aee46689dd8540cd4bb98da03dcc9d171ce3efd99a9173"
CHARS = "".join(chr(c) for c in range(32, 127))
LETTER_SPACING = {8: 1, 16: 1, 24: 2, 40: 3}


def rasterize(path, cell):
    # Rasterize each size directly with FreeType's monochrome hinting, not by
    # scaling a smaller bitmap. Use one baseline for the entire ASCII set.
    for ppem in range(cell, 0, -1):
        font = ImageFont.truetype(str(path), ppem, layout_engine=ImageFont.Layout.BASIC)
        glyphs = []
        for char in CHARS:
            mask, offset = font.getmask2(char, mode="1", anchor="ls")
            ink = Image.frombytes("L", mask.size, bytes(mask))
            box = ink.getbbox()
            glyphs.append((ink, box, offset))
        top = min(offset[1] + box[1] for _, box, offset in glyphs if box)
        bottom = max(offset[1] + box[3] for _, box, offset in glyphs if box)
        width = max(box[2] - box[0] for _, box, _ in glyphs if box)
        if bottom - top <= cell and width <= cell:
            break
    baseline = (cell - (bottom - top)) // 2 - top
    advances = [max(1, round(font.getlength(char)),
                    max(0, offset[0] + box[0]) + box[2] - box[0] if box else 0)
                for char, (_, box, offset) in zip(CHARS, glyphs)]
    digit_advance = max(advances[ord(c) - 32] for c in "0123456789")
    for char in "0123456789":
        advances[ord(char) - 32] = digit_advance
    # Add breathing room for camera video. Cap at the storage cell width so
    # timestamp's existing worst-case protection reservation remains valid.
    advances = [min(cell, advance + LETTER_SPACING[cell]) for advance in advances]
    result = []
    for char, (ink, box, offset), advance in zip(CHARS, glyphs, advances):
        assert 0 < advance <= cell
        image = Image.new("1", (cell, cell))
        if box:
            x = ((advance - (box[2] - box[0])) // 2 if char.isdigit()
                 else max(0, offset[0] + box[0]))
            y = baseline + offset[1] + box[1]
            assert 0 <= y and y + box[3] - box[1] <= cell
            assert 0 <= x and x + box[2] - box[0] <= advance
            image.paste(ink.crop(box).convert("1", dither=Image.Dither.NONE), (x, y))
        result.append(image)
    assert not result[0].getbbox()
    assert all(image.getbbox() for image in result[1:])
    assert len(set(advances[ord(c) - 32] for c in "0123456789")) == 1
    return result, ppem, baseline, advances


def header(tables):
    lines = [
        "/* Ameba OSD Sans - generated monochrome ASCII font data (SIL OFL 1.1).",
        " * Derived from Liberation Sans Bold 2.1.5; see fonts/OFL.txt.",
        " * Digitized data copyright (c) 2010 Google Corporation.",
        " * Copyright (c) 2012 Red Hat, Inc.",
        " * Generated by tools/generate_font.py; do not edit glyph bytes manually.",
        " * Rows are byte-aligned, MSB first. No runtime grayscale or font engine.",
        " */",
        "#ifndef _VIDEO_OSD_FONT_DATA_H_",
        "#define _VIDEO_OSD_FONT_DATA_H_",
        "#include <stdint.h>",
    ]
    for images, ppem, baseline, _ in tables:
        cell = images[0].height
        scale = cell // 8
        lines += ["", f"/* {cell}x{cell} cells, native {ppem} ppem, baseline {baseline}. */",
                  f"static const uint8_t video_osd_font_{cell}[95][{cell * scale}] = {{"]
        for code, image in enumerate(images, 32):
            data = image.tobytes()
            assert len(data) == cell * scale
            lines.append(f"\t/* ASCII 0x{code:02x} */")
            lines.append("\t{")
            for start in range(0, len(data), 12):
                lines.append("\t\t" + ", ".join(f"0x{x:02x}" for x in data[start:start + 12]) + ",")
            lines.append("\t},")
        lines.append("};")
    lines += ["", "/* Scales 1/2/3/5: tabular digits and 1/1/2/3-pixel spacing, capped at cell width. */",
              "static const uint8_t video_osd_font_advance[4][95] = {"]
    for _, _, _, advances in tables:
        lines.append("\t{")
        for start in range(0, len(advances), 16):
            lines.append("\t\t" + ", ".join(str(x) for x in advances[start:start + 16]) + ",")
        lines.append("\t},")
    lines.append("};")
    return "\n".join(lines + ["", "#endif", ""])


def text_image(table, text, fixed=False):
    glyphs, _, _, advances = table
    cell = glyphs[0].height
    width = len(text) * cell if fixed else sum(advances[ord(c) - 32] for c in text)
    line = Image.new("1", (width, cell))
    x = 0
    for char in text:
        glyph = glyphs[ord(char) - 32]
        advance = advances[ord(char) - 32]
        if fixed:
            box = glyph.getbbox()
            if box:
                line.paste(glyph.crop(box), (x + (cell - (box[2] - box[0])) // 2, box[1]))
            x += cell
        else:
            line.paste(glyph.crop((0, 0, advance, cell)), (x, 0))
            x += advance
    assert x == width
    return line


def preview(tables, output):
    # Display exact generated bits. The enlarged rows use nearest-neighbor only.
    samples = ["2026-09-22 18:35:07", "Person 98%  ABC xyz gjpqy", "0123456789 /-: @MWil"]
    image = Image.new("RGB", (1000, 1100), "#202832")
    draw = ImageDraw.Draw(image)
    y = 12
    for table in tables:
        cell = table[0][0].height
        scale = cell // 8
        draw.text((16, y), f"Ameba OSD Sans Bold | scale={scale} | {cell}px | proportional, tabular digits | 1-bit", fill="white")
        y += 24
        for text in samples:
            line = text_image(table, text)
            image.paste("white", (16, y), line)
            y += cell + 6
        text = samples[0]
        line = text_image(table, text)
        enlarged = line.resize((line.width * 2, cell * 2), Image.Resampling.NEAREST)
        image.paste("#d6e8ff", (16, y), enlarged)
        y += cell * 2 + 25
    for fixed in (True, False):
        line = text_image(tables[2], "1970-01-01 00:01:56", fixed)
        draw.text((16, y), f"{'Fixed-cell layout' if fixed else 'Proportional with spacing'} | {line.width}px", fill="white")
        y += 22
        image.paste("white", (16, y), line)
        y += 34
    image.crop((0, 0, 1000, y)).save(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--check", type=Path)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != FONT_SHA256:
        parser.error("Expected the unmodified Liberation Sans Bold 2.1.5 TTF")
    tables = [rasterize(args.font, cell) for cell in (8, 16, 24, 40)]
    output = header(tables)
    if args.check:
        if args.check.read_text(encoding="utf-8") != output:
            raise SystemExit("Font data differs; check Pillow/FreeType versions")
        print("PASS: all 380 glyphs, bounds, tabular digits, advances and generated header match")
    elif not args.preview:
        print(output, end="")
    if args.preview:
        preview(tables, args.preview)


if __name__ == "__main__":
    main()
